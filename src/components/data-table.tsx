export const schema = z.object({
  id: z.number(),
  header: z.string(),
  type: z.string(),
  status: z.string(),
  target: z.string(),
  limit: z.string(),
  reviewer: z.string(),
});

function DragHandle({ id }: { id: number }) {
  const { attributes, listeners } = useSortable({ id });

  return (
    <Button
      {...attributes}
      {...listeners}
      variant="ghost"
      size="icon"
      className="size-7 text-muted-foreground hover:bg-transparent"
    >
      <GripVerticalIcon className="size-3 text-muted-foreground" />
      <span className="sr-only">Drag to reorder</span>
    </Button>
  );
}

const inputCellClass =
  'h-8 w-16 border-transparent bg-transparent text-right shadow-none hover:bg-input/30 focus-visible:border focus-visible:bg-background dark:bg-transparent dark:hover:bg-input/30 dark:focus-visible:bg-input/30';

function EditableCell({
  id,
  label,
  defaultValue,
  rowHeader,
}: {
  id: string;
  label: string;
  defaultValue: string;
  rowHeader: string;
}) {
  return (
    <form
      onSubmit={e => {
        e.preventDefault();
        toast.promise(new Promise(resolve => setTimeout(resolve, 1000)), {
          loading: `Saving ${rowHeader}`,
          success: 'Done',
          error: 'Error',
        });
      }}
    >
      <Label htmlFor={id} className="sr-only">
        {label}
      </Label>
      <Input className={inputCellClass} defaultValue={defaultValue} id={id} />
    </form>
  );
}

